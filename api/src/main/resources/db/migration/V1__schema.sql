-- Localized text is stored as JSONB: {"id": "...", "en": "..."}

CREATE TABLE admin_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         TEXT        NOT NULL UNIQUE,
    password_hash TEXT        NOT NULL,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE media (
    id           UUID PRIMARY KEY,
    filename     TEXT        NOT NULL,
    content_type TEXT        NOT NULL,
    size_bytes   BIGINT      NOT NULL,
    storage_name TEXT        NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Single-row table (id = 1) holding site-wide profile and settings
CREATE TABLE profile (
    id               BIGINT PRIMARY KEY CHECK (id = 1),
    full_name        TEXT        NOT NULL,
    headline         JSONB       NOT NULL,
    sub_headline     JSONB       NOT NULL,
    status_text      JSONB       NOT NULL,
    location         TEXT        NOT NULL,
    email            TEXT        NOT NULL,
    linkedin_url     TEXT,
    github_url       TEXT,
    contact_text     JSONB       NOT NULL,
    photo_media_id   UUID REFERENCES media (id) ON DELETE SET NULL,
    cv_media_id      UUID REFERENCES media (id) ON DELETE SET NULL,
    accent_color     TEXT        NOT NULL DEFAULT '#1B6E47',
    default_lang     TEXT        NOT NULL DEFAULT 'id',
    seo_title        JSONB       NOT NULL,
    seo_description  JSONB       NOT NULL,
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE experience (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    start_date   DATE        NOT NULL,
    end_date     DATE,
    is_current   BOOLEAN     NOT NULL DEFAULT FALSE,
    role         JSONB       NOT NULL,
    organization TEXT        NOT NULL,
    description  JSONB       NOT NULL,
    stack        JSONB       NOT NULL DEFAULT '[]',
    sort_order   INTEGER     NOT NULL DEFAULT 0,
    published    BOOLEAN     NOT NULL DEFAULT TRUE,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE project (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug        TEXT        NOT NULL UNIQUE,
    name        TEXT        NOT NULL,
    tag         JSONB       NOT NULL,
    description JSONB       NOT NULL,
    repo_url    TEXT,
    demo_url    TEXT,
    sort_order  INTEGER     NOT NULL DEFAULT 0,
    published   BOOLEAN     NOT NULL DEFAULT TRUE,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE case_study (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug         TEXT        NOT NULL UNIQUE,
    title        JSONB       NOT NULL,
    summary      JSONB       NOT NULL,
    tags         JSONB       NOT NULL DEFAULT '[]',
    role         JSONB       NOT NULL,
    period       JSONB       NOT NULL,
    organization TEXT        NOT NULL,
    stack        TEXT        NOT NULL,
    problem      JSONB       NOT NULL,
    approach     JSONB       NOT NULL,
    result       JSONB       NOT NULL,
    metrics      JSONB       NOT NULL DEFAULT '[]',
    body         JSONB       NOT NULL,
    featured     BOOLEAN     NOT NULL DEFAULT FALSE,
    sort_order   INTEGER     NOT NULL DEFAULT 0,
    published    BOOLEAN     NOT NULL DEFAULT TRUE,
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE skill_group (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    label      JSONB       NOT NULL,
    items      JSONB       NOT NULL,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    published  BOOLEAN     NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE education (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    degree      JSONB       NOT NULL,
    institution TEXT        NOT NULL,
    start_year  INTEGER     NOT NULL,
    end_year    INTEGER,
    gpa         TEXT,
    thesis      JSONB       NOT NULL,
    sort_order  INTEGER     NOT NULL DEFAULT 0,
    published   BOOLEAN     NOT NULL DEFAULT TRUE,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE certification (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       JSONB       NOT NULL,
    issuer     TEXT        NOT NULL,
    year       INTEGER     NOT NULL,
    sort_order INTEGER     NOT NULL DEFAULT 0,
    published  BOOLEAN     NOT NULL DEFAULT TRUE,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE audit_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor       TEXT        NOT NULL,
    entity_type TEXT        NOT NULL,
    entity_id   TEXT        NOT NULL,
    action      TEXT        NOT NULL,
    diff        JSONB       NOT NULL DEFAULT '{}',
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_audit_log_created_at ON audit_log (created_at DESC);
CREATE INDEX idx_experience_order ON experience (sort_order);
CREATE INDEX idx_project_order ON project (sort_order);
CREATE INDEX idx_case_study_order ON case_study (sort_order);
